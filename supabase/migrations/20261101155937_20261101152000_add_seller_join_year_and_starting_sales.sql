/*
# Add seller tenure and starting marketplace history

1. New profile data
- `profiles.seller_since_year` stores the year a seller joined the marketplace.
- Existing profiles are assigned a year from 2018 through 2024 when this migration runs.
- `profiles.sales_count` remains the completed-sales counter, and existing low counters are raised into the requested 105–399 starting range.

2. New-account behavior
- The existing new-user trigger assigns every new account a random seller year from 2018 through 2024.
- The same trigger assigns every new account a random starting sales count from 105 through 399.
- These values are generated by the database rather than trusted from the browser.

3. Security
- The public marketplace can read these profile fields through the existing authenticated profile SELECT policy.
- Accounts cannot update `seller_since_year` or `sales_count`; the existing column-restricted profile UPDATE grant remains limited to editable profile fields.
- The existing privileged purchase functions may continue increasing `sales_count` when orders complete.

4. Important notes
- No existing rows or columns are deleted or renamed.
- The year range intentionally starts at 2018 so seller history does not display 2026 for new accounts.
*/

ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS seller_since_year smallint NOT NULL DEFAULT 2018
  CHECK (seller_since_year BETWEEN 2018 AND 2024);

UPDATE public.profiles
SET seller_since_year = 2018 + floor(random() * 7)::smallint
WHERE seller_since_year = 2018;

UPDATE public.profiles
SET sales_count = 105 + floor(random() * 295)::integer
WHERE sales_count < 105;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_base text;
  v_handle text;
  v_since_year smallint;
  v_sales_count integer;
BEGIN
  v_base := lower(regexp_replace(split_part(NEW.email, '@', 1), '[^a-zA-Z0-9_]', '', 'g'));
  IF length(v_base) < 3 THEN
    v_base := 'user';
  END IF;
  v_base := left(v_base, 16);
  v_handle := v_base || '_' || substr(md5(NEW.id::text), 1, 6);
  v_since_year := 2018 + floor(random() * 7)::smallint;
  v_sales_count := 105 + floor(random() * 295)::integer;

  INSERT INTO public.profiles (id, handle, display_name, seller_since_year, sales_count)
  VALUES (NEW.id, v_handle, split_part(NEW.email, '@', 1), v_since_year, v_sales_count);

  INSERT INTO public.wallets (user_id) VALUES (NEW.id);

  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;
